// Builds a real beach for the Us mockups from Shellby's own layout code
// (src/main/beach.js), plus the classic crab, into beach-data.js.
// Run: node mockups/us-page/make-beach.js
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..', '..');
const B = require(path.join(root, 'src/main/beach'));
const stickers = require(path.join(root, 'src/main/stickers'));
const streaks = require(path.join(root, 'src/main/progression/streaks'));
const gifts = require(path.join(root, 'src/main/gifts'));

const DAY = 86400000;
const NOW = new Date(2026, 10, 13, 21).getTime();
const ago = d => NOW - d * DAY;

const NAMES = ['shellby', 'tidepool-api', 'rack-builder', 'label-cloud', 'harbor-site', 'dotfiles', 'cable-list', 'weekend-jam',
  'pixel-kit', 'notes-sync', 'atlas-forge', 'bugdex', 'reef-cam', 'hush'];
const SHIPS = [168, 42, 31, 22, 18, 3, 9, 1, 6, 4, 12, 15, 2, 7];
const MARKS = [['live', 'release', 'v1'], ['live', 'release'], ['release'], ['live'], ['live', 'release'], [], [], [], ['release'], [], ['live'], ['release', 'v1'], [], []];
const projects = {};
NAMES.forEach((name, i) => {
  const id = (i.toString(16) + 'a1b2c3d4e5f6a7b8').slice(0, 12);
  const first = ago(200 - i * 13);
  projects[id] = { name, firstShipAt: first, lastShipAt: first + 3 * DAY, ships: SHIPS[i], marks: MARKS[i] };
});

const findIds = ['pebble', 'sand-dollar', 'tiny-shell', 'driftwood', 'kelp', 'starfish', 'urchin-shell', 'conch',
  'sea-glass-green', 'sea-glass-blue', 'sea-glass-amber', 'sea-glass-red'];
const finds = Object.fromEntries(findIds.map((id, i) => [id, { n: 1 + (i % 3), first: ago(150 - i * 9), last: ago(5) }]));

const dayKey = t => { const d = new Date(t); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`; };
const days = Array.from({ length: 40 }, (_, i) => dayKey(ago(i)));
const plots = { 'c:\\code\\agent-hub': { name: 'agent-hub', lastSeen: ago(0) }, 'c:\\code\\3d-rack': { name: '3d-rack', lastSeen: ago(1) } };
const species = Object.fromEntries(['nullfish', 'racecrab', 'leakworm', 'offbyone', 'deadlock', 'flake', 'heisen', 'segfish', 'typo']
  .map(id => [id, { byDevice: { pc: 1 }, seen: 2, caught: 1 }]));

const view = B.view({
  stickerState: stickers.normalize({ projects }),
  streakState: streaks.normalize({ days, projects: plots }),
  findState: gifts.normalize({ items: finds }),
  bugState: { species },
  state: null,
  now: NOW,
});
// The finds' art comes from the catalogue the panel would send along.
const catalogue = Object.fromEntries(gifts.FINDS.map(f => [f.id, f]));
view.finds = view.finds.map(f => ({ ...catalogue[f.id], ...f }));

const skin = JSON.parse(fs.readFileSync(path.join(root, 'src/skins/classic.json'), 'utf8'));
fs.writeFileSync(path.join(__dirname, 'beach-data.js'),
  `// Generated by make-beach.js: a real beach layout and the classic crab.\nwindow.BEACH = ${JSON.stringify(view)};\nwindow.SKIN = ${JSON.stringify(skin)};\n`);
console.log(`castles ${view.castles.length}, finds ${view.finds.length}, width ${view.world.width}, plots ${view.plots.length}, pool ${!!view.pool}`);
